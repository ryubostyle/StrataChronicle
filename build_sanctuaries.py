# build_sanctuaries.py
import os
import yaml

def materialize_architecture():
    yml_path = "architecture.yml"
    if not os.path.exists(yml_path):
        print("⚠️ architecture.yml が見つかりません。")
        return

    with open(yml_path, 'r', encoding='utf-8') as f:
        config = yaml.safe_load(f)

    print("🏛️ [StrataChronicle Auto-Builder] 聖域の自動構築および自己ブートストラップを開始します...")

    sanctuaries = config.get("sanctuaries", [])

    # 1. 各聖域フォルダと動的初期化ファイルの構築
    for sanctuary in sanctuaries:
        name = sanctuary["name"]
        role = sanctuary["role"]
        
        if not os.path.exists(name):
            os.makedirs(name)
            print(f"  + 📁 聖域フォルダ生成: {name}/ ({role})")

        gitkeep_path = os.path.join(name, ".gitkeep")
        if not os.path.exists(gitkeep_path):
            with open(gitkeep_path, 'w', encoding='utf-8') as gk:
                pass

        init_path = os.path.join(name, "__init__.py")
        init_content = f'''import os
import yaml

CURRENT_ROOT = os.path.dirname(os.path.abspath(__file__))
REPOSITORY_ROOT = os.path.dirname(CURRENT_ROOT)
SANCTUARY_NAME = os.path.basename(CURRENT_ROOT)

def resolve_next_root():
    yml_path = os.path.join(REPOSITORY_ROOT, "architecture.yml")
    if os.path.exists(yml_path):
        try:
            with open(yml_path, 'r', encoding='utf-8') as f:
                config = yaml.safe_load(f)
            for s in config.get("sanctuaries", []):
                if s["name"] == SANCTUARY_NAME:
                    next_name = s.get("next")
                    if next_name:
                        return os.path.join(REPOSITORY_ROOT, next_name)
        except Exception as e:
            print(f"⚠️ 読み込みエラー: {{e}}")
    return CURRENT_ROOT

SANCTUARY_ROOT = CURRENT_ROOT
NEXT_ROOT = resolve_next_root()
'''
        with open(init_path, 'w', encoding='utf-8') as init_file:
            init_file.write(init_content)
        print(f"  + 📜 聖域トポロジ定着: {name}/__init__.py")

    # 2. 【エラートラップ & 自動生成】main.py がなければ自律的に生成・設定する
    main_py_path = "main.py"
    if not os.path.exists(main_py_path):
        print("  ⚡ [Bootstrap] main.py が検出されませんでした。自動生成機構を発動します...")
        generate_default_main_py(main_py_path)
    else:
        print("  ✓ [Bootstrap] main.py はすでに存在しています。")

    print("✨ [StrataChronicle Auto-Builder] すべての構築とブートストラップが完遂しました。")

def generate_default_main_py(target_path: str):
    """main.py が欠損している場合に動的トポロジ駆動型の標準パイプラインを自動生成する"""
    default_code = '''# main.py (Auto-generated by build_sanctuaries.py)
import os
import glob
import shutil
import yaml
from datetime import datetime

class DynamicCirculationPipeline:
    def __init__(self):
        self.root_dir = os.path.dirname(os.path.abspath(__file__))
        self.arch_path = os.path.join(self.root_dir, "architecture.yml")
        self.sanctuaries = self._load_architecture()

    def _load_architecture(self):
        if os.path.exists(self.arch_path):
            try:
                with open(self.arch_path, 'r', encoding='utf-8') as f:
                    config = yaml.safe_load(f)
                    return config.get("sanctuaries", [])
            except Exception as e:
                print(f"⚠️ architecture.yml の読み込みエラー: {e}")
        return [
            {"name": "Film", "next": "Projector"},
            {"name": "Projector", "next": "Screen"},
            {"name": "Screen", "next": "Theater"},
            {"name": "Theater", "next": None}
        ]

    def run_metabolism(self):
        print("🎬 [StrataChronicle] 自動生成された動的代謝サイクルを開始します...")
        for i in range(len(self.sanctuaries) - 1):
            curr = self.sanctuaries[i]["name"]
            nxt = self.sanctuaries[i + 1]["name"]
            src = os.path.join(self.root_dir, curr)
            dest = os.path.join(self.root_dir, nxt)

            if curr == "Film":
                self._process_film(src, dest)
            else:
                self._sweep(src, dest, f"[{curr} -> {nxt}]")

        self._crystallize()
        print("✨ [StrataChronicle] 代謝サイクルが完遂しました。")

    def _process_film(self, src: str, dest: str):
        if not os.path.exists(src): return
        os.makedirs(dest, exist_ok=True)
        for path in glob.glob(os.path.join(src, "*")):
            if os.path.isfile(path):
                base = os.path.basename(path)
                if base == ".gitkeep": continue
                try:
                    with open(path, 'r', encoding='utf-8') as f:
                        content = f.read().strip()
                except:
                    continue
                stem = os.path.splitext(base)[0]
                md = f\"\"\"---
title: "{stem}"
date: "{datetime.now().strftime('%Y-%m-%d')}"
stage: "Auto-Bootstrap"
---
# シナリオ台本: {stem}
{content}
\"\"\"
                dest_path = os.path.join(dest, f"{stem}.md")
                with open(dest_path, 'w', encoding='utf-8') as df:
                    df.write(md)
                os.remove(path)
                print(f"    🎞️ [Film] 変換代謝: {base} -> {stem}.md")

    def _sweep(self, src: str, dest: str, label: str):
        if not os.path.exists(src): return
        os.makedirs(dest, exist_ok=True)
        for path in glob.glob(os.path.join(src, "*")):
            if os.path.isfile(path):
                base = os.path.basename(path)
                if base == ".gitkeep": continue
                dest_path = os.path.join(dest, base)
                if os.path.exists(dest_path): os.remove(dest_path)
                shutil.move(path, dest_path)
                print(f"    ⚡ {label} 移送: {base}")

    def _crystallize(self):
        term = self.sanctuaries[-1]["name"]
        term_dir = os.path.join(self.root_dir, term)
        if not os.path.exists(term_dir): return
        for path in glob.glob(os.path.join(term_dir, "*")):
            if os.path.isfile(path):
                base = os.path.basename(path)
                if base == ".gitkeep": continue
                print(f"    💎✨ [{term}] 映写完了: {base}")

if __name__ == "__main__":
    Pipeline = DynamicCirculationPipeline()
    Pipeline.run_metabolism()
'''
    with open(target_path, 'w', encoding='utf-8') as f:
        f.write(default_code)
    print(  f"  + ✨ [Bootstrap] main.py が正常に自動生成・設定されました: {target_path}")

if __name__ == "__main__":
    materialize_architecture()
